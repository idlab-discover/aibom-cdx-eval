"""
analysis/report.py — generate a Markdown summary report from aggregated results.

Reads results/aggregated/<run-id>_summary.json and _rankings.csv and produces
results/aggregated/reports/<run-id>.md with summary tables and ranking tables.

Usage:
    python -m analysis.report --run-id <run-id>
"""

from __future__ import annotations

import csv
import json
import sys
from pathlib import Path

import click

EVAL_ROOT = Path(__file__).parent.parent
AGGREGATED_DIR = EVAL_ROOT / "results" / "aggregated"
REPORTS_DIR = AGGREGATED_DIR / "reports"

TASK_DESCRIPTIONS = {
    "T1":            "HF Model ID → AIBOM Generation",
    "T2":            "Source Code Scanning — Model Discovery",
    "T2-filesystem": "Filesystem Scanning — Model File Detection",
    "T3":            "Security Scanning",
}

PRIMARY_METRICS = {
    "T1":            "completeness_pct",
    "T2":            "f1",
    "T2-filesystem": "files_found",
    "T3":            "tpr",
}

DISPLAY_METRICS = {
    "T1": [
        ("completeness_pct", "Completeness %"),
        ("conformance_valid", "Conformance rate"),
        ("failure_rate", "Failure rate"),
        ("duration_mean", "Mean runtime (s)"),
    ],
    "T2": [
        ("f1",          "F1"),
        ("precision",   "Precision"),
        ("recall",      "Recall"),
        ("conformance_valid", "Conformance rate"),
        ("failure_rate", "Failure rate"),
        ("duration_mean", "Mean runtime (s)"),
    ],
    "T2-filesystem": [
        ("files_found", "Files found (mean)"),
        ("recall",      "Recall"),
        ("failure_rate", "Failure rate"),
        ("duration_mean", "Mean runtime (s)"),
    ],
    "T3": [
        ("tpr",         "TPR"),
        ("fpr",         "FPR"),
        ("failure_rate", "Failure rate"),
        ("duration_mean", "Mean runtime (s)"),
    ],
}


@click.command()
@click.option("--run-id", required=True)
def main(run_id: str) -> None:
    """Generate a Markdown report for a completed aggregated run."""
    summary_path = AGGREGATED_DIR / f"{run_id}_summary.json"
    rankings_path = AGGREGATED_DIR / f"{run_id}_rankings.csv"

    if not summary_path.exists():
        click.echo(f"Summary not found: {summary_path}", err=True)
        sys.exit(1)

    with open(summary_path) as f:
        summary = json.load(f)

    rankings = _load_csv(rankings_path) if rankings_path.exists() else []

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    report_path = REPORTS_DIR / f"{run_id}.md"

    lines = _build_report(run_id, summary, rankings)
    report_path.write_text("\n".join(lines))
    click.echo(f"Report written to: {report_path}")


# ------------------------------------------------------------------ #
# Report builder                                                       #
# ------------------------------------------------------------------ #

def _build_report(
    run_id: str,
    summary: dict,
    rankings: list[dict],
) -> list[str]:
    lines: list[str] = []

    lines += [
        f"# Evaluation Report — Run `{run_id}`",
        "",
        "Generated by `analysis/report.py`.",
        "",
        "## Overview",
        "",
    ]

    # Group summary by task
    by_task: dict[str, list[dict]] = {}
    for entry in summary.values():
        task = entry["task"]
        by_task.setdefault(task, []).append(entry)

    for task in sorted(by_task):
        desc = TASK_DESCRIPTIONS.get(task, task)
        entries = by_task[task]
        metric_cols = DISPLAY_METRICS.get(task, [])

        lines += [f"## Task {task} — {desc}", ""]

        # Rankings table for this task
        task_rankings = [r for r in rankings if r.get("task") == task]
        if task_rankings:
            lines += ["### Rankings", ""]
            lines += _rankings_table(task_rankings)
            lines.append("")

        # Detailed metrics table
        lines += ["### Detailed Metrics", ""]
        lines += _metrics_table(entries, metric_cols)
        lines.append("")

    return lines


def _rankings_table(rows: list[dict]) -> list[str]:
    header = "| Rank | Tool | Raw Score | Normalized (0–1) |"
    sep    = "|------|------|-----------|-----------------|"
    lines  = [header, sep]
    for row in sorted(rows, key=lambda r: int(r.get("rank", 99))):
        raw  = _fmt(row.get("raw_score"))
        norm = _fmt(row.get("normalized_score"))
        lines.append(f"| {row['rank']} | {row['tool']} | {raw} | {norm} |")
    return lines


def _metrics_table(entries: list[dict], metric_cols: list[tuple[str, str]]) -> list[str]:
    if not metric_cols:
        return ["*(no metrics configured)*"]

    header = "| Tool | " + " | ".join(label for _, label in metric_cols) + " |"
    sep    = "|------|" + "|".join("---" for _ in metric_cols) + "|"
    lines  = [header, sep]

    for entry in sorted(entries, key=lambda e: e["tool"]):
        tool = entry["tool"]
        cells = []
        for key, _ in metric_cols:
            if key in ("failure_rate", "duration_mean", "duration_min", "duration_max"):
                val = entry.get(key)
            else:
                metric_agg = entry.get("metrics", {}).get(key)
                val = metric_agg["mean"] if isinstance(metric_agg, dict) else None
            cells.append(_fmt(val))
        lines.append(f"| {tool} | " + " | ".join(cells) + " |")

    return lines


def _load_csv(path: Path) -> list[dict]:
    with open(path, newline="") as f:
        return list(csv.DictReader(f))


def _fmt(val: object) -> str:
    if val is None:
        return "—"
    if isinstance(val, bool):
        return "✓" if val else "✗"
    if isinstance(val, float):
        return f"{val:.4f}"
    return str(val)


if __name__ == "__main__":
    main()
