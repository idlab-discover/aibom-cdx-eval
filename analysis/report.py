"""
analysis/report.py — generate a Markdown summary report from aggregated results.

Reads results/aggregated/<run-id>_summary.json and produces:
  results/aggregated/reports/<run-id>.md

Sections:
  T1  — HF Model ID → AIBOM performance
  T2  — Reliability / failure rate
  T3  — Model discovery (precision / recall / F1)
  T4-G1 — CycloneDX quality for HF-ID tools
  T4-G2 — CycloneDX quality for source-scan tools

Usage:
    python -m analysis.report --run-id <run-id>
    uv run eval report --run-id <run-id>
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

import click

EVAL_ROOT = Path(__file__).parent.parent
AGGREGATED_DIR = EVAL_ROOT / "results" / "aggregated"
REPORTS_DIR = AGGREGATED_DIR / "reports"

SUB_TASK_DESCRIPTIONS = {
    "T1":    "HF Model ID → AIBOM — Performance",
    "T2":    "HF Model ID → AIBOM — Reliability",
    "T3":    "Source-Code Scan — Model Discovery",
    "T4-G1": "CycloneDX Quality (HF-model-ID tools)",
    "T4-G2": "CycloneDX Quality (source-scan tools)",
}


@click.command()
@click.option("--run-id", required=True)
def main(run_id: str) -> None:
    """Generate a Markdown report for a completed aggregated run."""
    summary_path = AGGREGATED_DIR / f"{run_id}_summary.json"
    if not summary_path.exists():
        click.echo(f"Summary not found: {summary_path}", err=True)
        sys.exit(1)

    with open(summary_path) as f:
        summary = json.load(f)

    REPORTS_DIR.mkdir(parents=True, exist_ok=True)
    report_path = REPORTS_DIR / f"{run_id}.md"
    report_path.write_text("\n".join(_build_report(run_id, summary)))
    click.echo(f"Report written to: {report_path}")


# ------------------------------------------------------------------ #
# Builder                                                              #
# ------------------------------------------------------------------ #

def _build_report(run_id: str, summary: dict) -> list[str]:
    lines: list[str] = [
        f"# Evaluation Report — Run `{run_id}`",
        "",
        "Generated by `analysis/report.py`.",
        "",
    ]

    by_subtask: dict[str, list[dict]] = {}
    for entry in summary.values():
        st = entry["sub_task"]
        by_subtask.setdefault(st, []).append(entry)

    for sub_task in ["T1", "T2", "T3", "T4-G1", "T4-G2"]:
        entries = by_subtask.get(sub_task)
        if not entries:
            continue
        desc = SUB_TASK_DESCRIPTIONS.get(sub_task, sub_task)
        lines += [f"## {sub_task} — {desc}", ""]
        if sub_task == "T1":
            lines += _t1_table(entries)
        elif sub_task == "T2":
            lines += _t2_table(entries)
        elif sub_task == "T3":
            lines += _t3_table(entries)
        elif sub_task in ("T4-G1", "T4-G2"):
            lines += _t4_table(entries)
        lines.append("")

    return lines


def _t1_table(entries: list[dict]) -> list[str]:
    cols = [
        ("normalized_throughput",      "Throughput (fields/s)"),
        ("size_normalized_throughput", "Size-norm throughput"),
        ("fields_present",             "Fields present (mean)"),
        ("duration_seconds",           "Duration (s, mean)"),
    ]
    return _metric_table(entries, cols, extra_cols=[("success_rate", "Success rate")])


def _t2_table(entries: list[dict]) -> list[str]:
    header = "| Tool | Success rate | Failure rate | timeout | network_error | parse_error | crash | missing_output | Retries (mean) |"
    sep    = "|------|-------------|-------------|---------|---------------|-------------|-------|----------------|---------------|"
    lines  = [header, sep]
    for e in sorted(entries, key=lambda x: x["tool"]):
        sr = _fmt(e.get("success_rate"))
        fr = _fmt(e.get("failure_rate"))
        br = e.get("error_breakdown", {})
        retries = _fmt(e.get("retries_mean"))
        row = (
            f"| {e['tool']} | {sr} | {fr}"
            f" | {br.get('timeout', 0)}"
            f" | {br.get('network_error', 0)}"
            f" | {br.get('parse_error', 0)}"
            f" | {br.get('crash', 0)}"
            f" | {br.get('missing_output', 0)}"
            f" | {retries} |"
        )
        lines.append(row)
    return lines


def _t3_table(entries: list[dict]) -> list[str]:
    cols = [
        ("f1",        "F1"),
        ("precision", "Precision"),
        ("recall",    "Recall"),
    ]
    return _metric_table(entries, cols)


def _t4_table(entries: list[dict]) -> list[str]:
    cols = [
        ("cdx_completeness_pct_v16",      "Completeness v1.6 (%)"),
        ("cdx_completeness_pct_v17",      "Completeness v1.7 (%)"),
        ("cdx_conformance_pass_rate_v16", "Conformance v1.6 rate"),
        ("cdx_conformance_pass_rate_v17", "Conformance v1.7 rate"),
    ]
    header = "| Tool | " + " | ".join(label for _, label in cols) + " |"
    sep    = "|------|" + "|".join("---" for _ in cols) + "|"
    lines  = [header, sep]
    for e in sorted(entries, key=lambda x: x["tool"]):
        cells = []
        for key, _ in cols:
            # conformance_pass_rate is stored directly, completeness inside metrics dict
            val = e.get("metrics", {}).get(key)
            if isinstance(val, dict):
                val = val.get("mean")
            cells.append(_fmt(val))
        lines.append(f"| {e['tool']} | " + " | ".join(cells) + " |")
    return lines


def _metric_table(
    entries: list[dict],
    metric_cols: list[tuple[str, str]],
    extra_cols: list[tuple[str, str]] | None = None,
) -> list[str]:
    extra_cols = extra_cols or []
    all_cols = extra_cols + metric_cols
    header = "| Tool | " + " | ".join(label for _, label in all_cols) + " |"
    sep    = "|------|" + "|".join("---" for _ in all_cols) + "|"
    lines  = [header, sep]
    for e in sorted(entries, key=lambda x: x["tool"]):
        cells = []
        for key, _ in all_cols:
            if key in ("success_rate", "failure_rate", "retries_mean"):
                val = e.get(key)
            else:
                agg = e.get("metrics", {}).get(key)
                val = agg["mean"] if isinstance(agg, dict) else None
            cells.append(_fmt(val))
        lines.append(f"| {e['tool']} | " + " | ".join(cells) + " |")
    return lines


# ------------------------------------------------------------------ #
# Helpers                                                              #
# ------------------------------------------------------------------ #

def _fmt(val: object) -> str:
    if val is None:
        return "—"
    if isinstance(val, bool):
        return "✓" if val else "✗"
    if isinstance(val, float):
        return f"{val:.4f}"
    return str(val)


if __name__ == "__main__":
    main()
